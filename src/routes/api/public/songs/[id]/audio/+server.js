import { json } from "@sveltejs/kit";
import {
  GetObjectCommand,
  HeadObjectCommand
} from "@aws-sdk/client-s3";

import { prisma } from "../../../../../../lib/server/prisma.js";
import {
  r2BucketName,
  r2Client
} from "../../../../../../lib/server/r2.js";

/**
 * Return JSON without allowing browser or intermediary caching.
 *
 * @param {object} body
 * @param {number} status
 * @param {HeadersInit} [additionalHeaders]
 * @returns {Response}
 */
function noStoreJson(body, status = 200, additionalHeaders = {}) {
  const headers = new Headers(additionalHeaders);
  headers.set("Cache-Control", "no-store");

  return json(body, { status, headers });
}

/**
 * Validate a positive song ID from the URL.
 *
 * @param {string | undefined} value
 * @returns {number | null}
 */
function parseSongId(value) {
  if (
    typeof value !== "string" ||
    !/^[1-9]\d*$/.test(value)
  ) {
    return null;
  }

  const id = Number(value);

  return Number.isSafeInteger(id) ? id : null;
}

/**
 * Extract an AWS SDK error name.
 *
 * @param {unknown} error
 * @returns {string}
 */
function getErrorName(error) {
  if (typeof error !== "object" || error === null) {
    return "";
  }

  if ("name" in error && typeof error.name === "string") {
    return error.name;
  }

  if ("Code" in error && typeof error.Code === "string") {
    return error.Code;
  }

  return "";
}

/**
 * Validate a single HTTP byte-range header.
 *
 * Supported formats:
 * bytes=0-999
 * bytes=1000-
 * bytes=-500
 *
 * Multiple ranges are deliberately not supported.
 *
 * @param {string | null} rangeHeader
 * @returns {{ valid: boolean, value: string | null }}
 */
function parseRangeHeader(rangeHeader) {
  if (!rangeHeader) {
    return {
      valid: true,
      value: null
    };
  }

  const value = rangeHeader.trim();

  const match = value.match(/^bytes=(\d*)-(\d*)$/i);

  if (!match || (!match[1] && !match[2])) {
    return {
      valid: false,
      value: null
    };
  }

  const start = match[1] === "" ? null : Number(match[1]);
  const end = match[2] === "" ? null : Number(match[2]);

  if (
    (start !== null && !Number.isSafeInteger(start)) ||
    (end !== null && !Number.isSafeInteger(end))
  ) {
    return {
      valid: false,
      value: null
    };
  }

  if (start === null && end === 0) {
    return {
      valid: false,
      value: null
    };
  }

  if (
    start !== null &&
    end !== null &&
    end < start
  ) {
    return {
      valid: false,
      value: null
    };
  }

  return {
    valid: true,
    value
  };
}

/**
 * Return HTTP 416 for an unsatisfiable byte range.
 * Retrieve the object size so Content-Range can be supplied.
 *
 * @param {string} fileKey
 * @returns {Promise<Response>}
 */
async function rangeNotSatisfiable(fileKey) {
  /** @type {number | null} */
  let fileSize = null;

  try {
    const metadata = await r2Client.send(
      new HeadObjectCommand({
        Bucket: r2BucketName,
        Key: fileKey
      })
    );

    if (
      typeof metadata.ContentLength === "number" &&
      Number.isSafeInteger(metadata.ContentLength)
    ) {
      fileSize = metadata.ContentLength;
    }
  } catch (error) {
    console.error(
      "Unable to retrieve audio size for an invalid range:",
      error
    );
  }

  const headers = new Headers();

  if (fileSize !== null) {
    headers.set(
      "Content-Range",
      `bytes */${fileSize}`
    );
  }

  return noStoreJson(
    { error: "Requested byte range is not satisfiable." },
    416,
    headers
  );
}

/**
 * Stream published song audio from private Cloudflare R2.
 *
 * Route:
 * GET /api/public/songs/:id/audio
 *
 * @param {import("@sveltejs/kit").RequestEvent} event
 * @returns {Promise<Response>}
 */
export async function GET({ params, request }) {
  const songId = parseSongId(params.id);

  if (songId === null) {
    return noStoreJson(
      { error: "Song not found." },
      404
    );
  }

  // Check current publication eligibility on every request.
  let song;

  try {
    song = await prisma.song.findFirst({
      where: {
        id: songId,
        isPublished: true,
        deletionPending: false
      },
      select: {
        fileKey: true
      }
    });
  } catch (error) {
    console.error("Public audio song lookup failed:", error);

    return noStoreJson(
      { error: "Unable to retrieve audio right now." },
      500
    );
  }

  // Unpublished, pending-deletion and nonexistent songs
  // must receive the same public response.
  if (!song) {
    return noStoreJson(
      { error: "Song not found." },
      404
    );
  }

  const fileKey = song.fileKey;

  // Accept only the UUID-based MP3 keys generated by uploads.
  const validFileKey =
    /^songs\/[0-9a-f]{8}-[0-9a-f]{4}-4[0-9a-f]{3}-[89ab][0-9a-f]{3}-[0-9a-f]{12}\.mp3$/i;

  if (!validFileKey.test(fileKey)) {
    console.error(
      "Song has an invalid public audio storage reference.",
      { songId }
    );

    return noStoreJson(
      { error: "Song not found." },
      404
    );
  }

  // Validate the optional Range header before contacting R2.
  const parsedRange = parseRangeHeader(
    request.headers.get("range")
  );

  if (!parsedRange.valid) {
    return rangeNotSatisfiable(fileKey);
  }

  /** @type {import("@aws-sdk/client-s3").GetObjectCommandInput} */
  const getObjectInput = {
    Bucket: r2BucketName,
    Key: fileKey
  };

  if (parsedRange.value) {
    getObjectInput.Range = parsedRange.value;
  }

  let audioObject;

  // Retrieve either the full MP3 or the requested byte range.
  try {
    audioObject = await r2Client.send(
      new GetObjectCommand(getObjectInput)
    );
  } catch (error) {
    const errorName = getErrorName(error);

    if (
      errorName === "InvalidRange" ||
      errorName === "RequestedRangeNotSatisfiable"
    ) {
      return rangeNotSatisfiable(fileKey);
    }

    if (
      errorName === "NoSuchKey" ||
      errorName === "NotFound" ||
      errorName === "NoSuchObject"
    ) {
      return noStoreJson(
        { error: "Song not found." },
        404
      );
    }

    console.error(
      "Public R2 audio retrieval failed:",
      error
    );

    return noStoreJson(
      { error: "Unable to retrieve audio right now." },
      502
    );
  }

  if (!audioObject.Body) {
    console.error(
      "R2 returned no public audio stream.",
      { songId }
    );

    return noStoreJson(
      { error: "Audio stream is unavailable." },
      502
    );
  }

  const headers = new Headers({
    "Content-Type": "audio/mpeg",
    "Accept-Ranges": "bytes",
    "Cache-Control": "no-store",
    "X-Content-Type-Options": "nosniff",
    "Content-Disposition": "inline"
  });

  if (typeof audioObject.ContentLength === "number") {
    headers.set(
      "Content-Length",
      String(audioObject.ContentLength)
    );
  }

  if (audioObject.ContentRange) {
    headers.set(
      "Content-Range",
      audioObject.ContentRange
    );
  }

  if (audioObject.ETag) {
    headers.set("ETag", audioObject.ETag);
  }

  if (audioObject.LastModified) {
    headers.set(
      "Last-Modified",
      audioObject.LastModified.toUTCString()
    );
  }

  // A response containing Content-Range is a partial response.
  const status = audioObject.ContentRange ? 206 : 200;

  return new Response(
    audioObject.Body.transformToWebStream(),
    {
      status,
      headers
    }
  );
}